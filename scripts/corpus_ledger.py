"""Write results/corpus/LEDGER.md from results/corpus/ledger.csv and funnel.csv.

    python scripts/corpus_ledger.py

ledger.csv has one row per defect reported to authors in batches 1-8 (October 2026; repositories by ID
only): how it was first found and whether `physverify scan` recovers it with no script. funnel.csv has
one row per batch: drawn, out of scope, otherwise not tested, tested, and what testing found. All the
totals in LEDGER.md are computed here, so they cannot drift from the rows. The classification is the
one in FINDINGS_BY_METHOD.md (2026-10-23). Counts hold for these batches only; not a bug rate.
"""
import collections
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parents[1] / "results" / "corpus"
ORDER = ["physverify check", "code does not run", "script reference", "reading, then a run"]
MEANING = {
    "physverify check": "a physverify check that needs no answer written for that code failed",
    "code does not run": "found by running the code at all (crash, missing import, removed function)",
    "script reference": "the reference written in the repository's test script disagreed",
    "reading, then a run": "found by reading the code, then confirmed by a run in the sandbox",
}


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    return "\n".join(out + ["| " + " | ".join(str(x) for x in r) + " |" for r in rows])


def main(out=HERE / "LEDGER.md"):
    rows = list(csv.DictReader(open(HERE / "ledger.csv", encoding="utf-8")))
    funnel = list(csv.DictReader(open(HERE / "funnel.csv", encoding="utf-8")))
    for b in funnel:
        parts = sum(int(b[k]) for k in ("out_of_scope", "other_not_tested", "tested"))
        assert parts == int(b["drawn"]), f"batch {b['batch']}: parts {parts} != drawn {b['drawn']}"
    n = len(rows)
    by = collections.defaultdict(list)
    for r in rows:
        by[r["found_by"]].append(r)
    reports = len({r["id"] for r in rows})
    scan = sum(int(r["scan_recovers"]) for r in rows)
    S = ["# Ledger of corpus findings (generated)",
         "Generated by `scripts/corpus_ledger.py` from `ledger.csv` (one row per defect) and `funnel.csv` (one row "
         "per batch); do not edit by hand. It covers the defects reported to authors from batches 1 to 8 (October "
         "2026), classified as in [FINDINGS_BY_METHOD.md](FINDINGS_BY_METHOD.md). Repositories are named by ID only. "
         "The counts describe these batches; they are not a bug rate for physics code.",
         f"## How each of the {n} defects was first found",
         table(["found by", "defects", "repositories", "what it means"],
               [[k, len(by[k]), len({r["id"] for r in by[k]}), MEANING[k]] for k in ORDER]
               + [["total", n, reports, "a repository can appear in two rows"]]),
         f"`physverify scan`, with no script, recovers {scan} of the {n} "
         f"({sum(r['note'] == 'partly' for r in rows if int(r['scan_recovers']))} of them only in part).",
         "## Funnel per batch",
         table(["batch", "drawn", "out of scope", "otherwise not tested", "tested",
                "repositories with a confirmed defect", "confirmed defects"],
               [[b["batch"], b["drawn"], b["out_of_scope"], b["other_not_tested"], b["tested"],
                 b["repos_with_confirmed_defect"], b["confirmed_defects"] or "not counted"] for b in funnel]),
         "Batch 8 (60 maintained libraries, all tested; reports posted to 15) and the later daily batches are not "
         "in the funnel because their exclusions were not recorded per reason. Batch 7 counts repositories with a "
         "confirmed defect, not defects.",
         "## Defects",
         table(["ID", "found by", "check", "scan recovers"],
               [[r["id"], r["found_by"], r["check"] or "-",
                 ("partly" if r["note"] == "partly" else "yes") if int(r["scan_recovers"]) else "no"] for r in rows])]
    Path(out).write_text("\n\n".join(S) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
